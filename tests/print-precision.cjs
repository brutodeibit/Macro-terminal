'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const js=fs.readFileSync('v7-ui.js','utf8'),ctx={window:{},esc:x=>String(x),v7PrintAllowed:()=>true};
vm.createContext(ctx);
vm.runInContext(js.slice(js.indexOf('function v7PrintRecord'),js.indexOf('function v7LabelLayout')),ctx);
const print={realPrint:true,price:150,timestamp:'2026-11-20',timestampPrecision:'date',sourceMode:'PROVIDER_REPORTED'};
const candle={ts:Date.parse('2026-11-20T14:30:00Z')/1000};
assert(ctx.v7PrintRecord(print));
assert(ctx.v7PrintCanOverlay(print,'1d'));
assert(!ctx.v7PrintCanOverlay(print,'1h'));
assert.equal(ctx.v7PrintEpoch(print,[candle],'1d'),candle.ts);
assert(Number.isNaN(ctx.v7PrintEpoch(print,[],'1d')));
assert(Number.isNaN(ctx.v7PrintEpoch(print,[candle],'1h')));
const precise={...print,timestamp:'2026-11-20T15:01:05Z',timestampPrecision:'second'};
assert.equal(ctx.v7PrintEpoch(precise,[candle],'1h'),Date.parse(precise.timestamp)/1000);
assert(!ctx.v7PrintRecord({...print,price:null}));
const html=ctx.v7PrintCoverage({prints:[print]},'1h');
assert(html.includes('1 filas'));
assert(html.includes('0 filas con precisión suficiente'));
assert(html.includes('no implica dark pool'));
vm.runInContext(js.slice(js.indexOf('function v7CboePrints'),js.indexOf('async function v7LoadCboePrints')),ctx);
const columns='Trading Date Time,Publication Date Time,Trade ID,Symbol,Price,Price Currency,Price Notation,Executed Shares,Execution Venue,Market Mechanism,Modification Indicator,Deferral Or Enrichment Type';
const trade=(id,mechanism,change='',currency='EUR')=>
 [precise.timestamp,'2026-11-20T15:15:08Z',id,'DE0002635307',62.4,currency,'MONE',200,'BATF',mechanism,change,''].join(',');
const trades=ctx.v7CboePrints([columns,trade('X','OB'),trade('Y','DB'),trade('Y','DB','CANC'),trade('Z','DB','','USD')].join('\n'));
assert.equal(trades.length,1);
assert.equal(trades[0].category,'Fuera de libro');
console.log('Print precision: daily anchor, intraday exclusion, table retention and source classification OK');
