const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const html=fs.readFileSync('index.html','utf8');
const elem=()=>({innerHTML:'',classList:{add(){},remove(){}},querySelectorAll:()=>[]});
const ctx={console,window:{addEventListener(){}},document:{body:elem(),getElementById:elem,querySelector:elem,querySelectorAll:()=>[]},localStorage:{getItem:()=>null},setTimeout(){},setInterval(){},location:{protocol:'https:'}};
vm.createContext(ctx);
for(const script of html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/gi))vm.runInContext(script[1],ctx);
const day=n=>new Date(Date.now()+n*86400000).toISOString().slice(0,10);
ctx.m={ticker:'SPY',asOf:day(-7),retainedChain:true,profiles:[{expiration:day(-1),totalOpenInterest:100},{expiration:day(1),totalOpenInterest:0},{expiration:day(20),totalOpenInterest:100}]};
assert.equal(vm.runInContext('optionsUsableProfiles(m).length',ctx),2);
assert.equal(vm.runInContext('optionsSelectedProfile(m).expiration',ctx),day(20));
let notice=vm.runInContext('optionAvailabilityNotice(m)',ctx);
assert(notice.includes('última')||notice.includes('anterior'));
assert(notice.includes('Consultar vencimientos caducados (1)'));
vm.runInContext('window.__optShowExpired=true',ctx);
assert.equal(vm.runInContext('optionsUsableProfiles(m).length',ctx),3);
ctx.oldDate=day(-1);
vm.runInContext('window.__optExpiration=oldDate',ctx);
assert.equal(vm.runInContext('optionsSelectedProfile(m).expiration',ctx),day(-1));
assert(vm.runInContext('optionAvailabilityNotice(m)',ctx).includes('no representan posicionamiento vigente'));
assert(vm.runInContext('optionAvailabilityNotice({ticker:"NONE",profiles:[]})',ctx).includes('cotización no sustituye'));
console.log('Options recovery: expired history opt-in, explicit selection, default populated OI, dated retention and unavailable states OK');
